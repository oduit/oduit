def _generated_blocks_from_document(
    doc_path: Path,
) -> list[TechnicalDocumentationGeneratedBlock]:
    try:
        markdown = doc_path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return []
    try:
        blocks = parse_generated_blocks(markdown)
    except ValueError:
        return []
    generated: list[TechnicalDocumentationGeneratedBlock] = []
    for block in blocks:
        generated.append(
            TechnicalDocumentationGeneratedBlock(
                id=block.id,
                renderer=block.renderer,
                schema_version=block.schema_version,
                source_sha256=(
                    block.metadata.get("source_sha256")
                    if isinstance(block.metadata.get("source_sha256"), str)
                    else ""
                ),
                content_sha256=(
                    block.metadata.get("content_sha256")
                    if isinstance(block.metadata.get("content_sha256"), str)
                    else sha256_text(block.body)
                ),
                line_count=len(block.body.splitlines()),
            )
        )
    return generated


def _generated_blocks_from_list(
    data: Any,
) -> list[TechnicalDocumentationGeneratedBlock]:
    if not isinstance(data, list):
        return []
    generated: list[TechnicalDocumentationGeneratedBlock] = []
    for item in data:
        if not isinstance(item, dict):
            continue
        block_id = item.get("id")
        renderer = item.get("renderer")
        if not isinstance(block_id, str) or not isinstance(renderer, str):
            continue
        generated.append(
            TechnicalDocumentationGeneratedBlock(
                id=block_id,
                renderer=renderer,
                schema_version=str(
                    item.get("schema_version", "oduit.generated_markdown_block.v1")
                ),
                source_sha256=_optional_str(item.get("source_sha256")) or "",
                content_sha256=_optional_str(item.get("content_sha256")) or "",
                line_count=_optional_int(item.get("line_count")),
                updated_at=_optional_str(item.get("updated_at")),
            )
        )
    return generated


def _source_snapshot_from_dict(data: Any) -> DocumentationSourceSnapshot | None:
    if not isinstance(data, dict):
        return None
    files_data = data.get("files")
    if not isinstance(files_data, list):
        return None
    files: list[DocumentationTrackedFile] = []
    for item in files_data:
        if not isinstance(item, dict):
            return None
        path = item.get("path")
        category = item.get("category")
        if not isinstance(path, str) or not isinstance(category, str):
            return None
        files.append(
            DocumentationTrackedFile(
                path=path,
                category=category,
                size_bytes=_optional_int(item.get("size_bytes")),
                sha256=_optional_str(item.get("sha256")),
            )
        )
    return DocumentationSourceSnapshot(
        algorithm=str(data.get("algorithm", "sha256")),
        fingerprint=str(data.get("fingerprint", "")),
        file_count=int(data.get("file_count", len(files)) or 0),
        files=files,
    )


def _document_snapshot_from_dict(data: Any) -> DocumentationDocumentSnapshot | None:
    if not isinstance(data, dict):
        return None
    fingerprint = data.get("fingerprint")
    if not isinstance(fingerprint, str):
        return None
    return DocumentationDocumentSnapshot(
        algorithm=str(data.get("algorithm", "sha256")),
        fingerprint=fingerprint,
        size_bytes=_optional_int(data.get("size_bytes")),
        line_count=_optional_int(data.get("line_count")),
    )


def _optional_int(value: Any) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _optional_str(value: Any) -> str | None:
    return value if isinstance(value, str) else None


def _portable_path(path: Path, *, base_dir: Path | None = None) -> str:
    resolved = path.resolve(strict=False)
    for base in [base_dir, Path.cwd()]:
        if base is None:
            continue
        try:
            value = resolved.relative_to(base.resolve(strict=False)).as_posix()
        except ValueError:
            continue
        return value or "."
    return resolved.as_posix()


def _metadata_relative_path(
    path: Path,
    *,
    addon_root: Path,
    base_dir: Path | None = None,
) -> str:
    resolved_path = path.resolve(strict=False)
    resolved_root = addon_root.resolve(strict=False)
    try:
        return resolved_path.relative_to(resolved_root).as_posix()
    except ValueError:
        return _portable_path(resolved_path, base_dir=base_dir)



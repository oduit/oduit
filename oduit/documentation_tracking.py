def _diff_source_files(
    old_snapshot: DocumentationSourceSnapshot,
    new_snapshot: DocumentationSourceSnapshot,
) -> tuple[list[str], list[str], list[str]]:
    old_by_path = {file_entry.path: file_entry for file_entry in old_snapshot.files}
    new_by_path = {file_entry.path: file_entry for file_entry in new_snapshot.files}
    added_files = sorted(set(new_by_path) - set(old_by_path))
    removed_files = sorted(set(old_by_path) - set(new_by_path))
    changed_files = sorted(
        path
        for path in set(old_by_path) & set(new_by_path)
        if old_by_path[path].sha256 != new_by_path[path].sha256
    )
    return changed_files, added_files, removed_files


def _is_addon_root(path: Path) -> bool:
    return any((path / filename).exists() for filename in _MANIFEST_FILENAMES)


def _module_from_root(path: Path) -> str:
    return path.name


def _scan_addons_under(directory: Path) -> list[tuple[str, str]]:
    resolved_directory = directory.resolve(strict=False)
    if _is_addon_root(resolved_directory):
        return [(_module_from_root(resolved_directory), resolved_directory.as_posix())]
    if not resolved_directory.is_dir():
        return []
    result: list[tuple[str, str]] = []
    for child in sorted(resolved_directory.iterdir()):
        if child.is_dir() and _is_addon_root(child):
            result.append(
                (_module_from_root(child), child.resolve(strict=False).as_posix())
            )
    return result


def _resolve_select_path(select_dir: str, *, path_base_dir: Path | None) -> Path:
    selected = Path(select_dir).expanduser()
    if selected.is_absolute():
        return selected.resolve(strict=False)
    base = path_base_dir or Path.cwd()
    return (base / selected).resolve(strict=False)


def _resolve_metadata_path(value: str, *, base_dir: Path | None) -> Path:
    path = Path(value).expanduser()
    if path.is_absolute():
        return path.resolve(strict=False)
    if base_dir is None:
        return path.resolve(strict=False)
    return (base_dir / path).resolve(strict=False)


def _iter_addon_roots(
    addons_path: str,
    *,
    select_dir: str | None,
    path_base_dir: Path | None = None,
) -> list[tuple[str, str]]:
    addon_roots: list[tuple[str, str]] = []
    seen_roots: set[str] = set()
    configured_paths = [
        Path(configured_path).resolve(strict=False)
        for configured_path in AddonsPathManager(addons_path).get_configured_paths()
    ]

    candidate_directories: list[Path]
    if select_dir is not None:
        selected_path = _resolve_select_path(select_dir, path_base_dir=path_base_dir)
        if selected_path.exists():
            candidate_directories = [selected_path]
        else:
            candidate_directories = [
                base_path
                for base_path in configured_paths
                if base_path.name == select_dir
            ]
    else:
        candidate_directories = configured_paths

    for directory in candidate_directories:
        for module, addon_root in _scan_addons_under(directory):
            if addon_root in seen_roots:
                continue
            seen_roots.add(addon_root)
            addon_roots.append((module, addon_root))
    return addon_roots

def inspect_technical_documentation_status(
    *,
    addon_root: str | Path,
    module: str,
    path_base_dir: Path | None = None,
) -> TechnicalDocumentationStatus:
    """Return tracking status for one addon."""

    root = Path(addon_root).resolve(strict=False)
    doc_path, metadata_path = technical_doc_paths(root)
    storage_base = (
        path_base_dir.resolve(strict=False)
        if path_base_dir is not None
        else Path.cwd().resolve(strict=False)
    )
    display_root = _portable_path(root, base_dir=storage_base)
    display_doc = _portable_path(doc_path, base_dir=storage_base)
    display_metadata = _portable_path(metadata_path, base_dir=storage_base)
    has_document = doc_path.exists()
    has_metadata = metadata_path.exists()
    generated_by_oduit = has_document and _document_has_generated_header(doc_path)

    if not has_document and not has_metadata:
        return TechnicalDocumentationStatus(
            module=module,
            addon_root=display_root,
            doc_path=display_doc,
            metadata_path=display_metadata,
            status="missing",
        )

    if has_document and not has_metadata:
        remediation = []
        if generated_by_oduit:
            remediation.append(
                "Regenerate the technical documentation with oduit to create "
                "tracking metadata."
            )
        return TechnicalDocumentationStatus(
            module=module,
            addon_root=display_root,
            doc_path=display_doc,
            metadata_path=display_metadata,
            status="untracked",
            has_document=True,
            generated_by_oduit=generated_by_oduit,
            remediation=remediation,
        )

    metadata, warnings = load_technical_documentation_metadata(metadata_path)
    if metadata is None:
        return TechnicalDocumentationStatus(
            module=module,
            addon_root=display_root,
            doc_path=display_doc,
            metadata_path=display_metadata,
            status="metadata_invalid",
            has_document=has_document,
            has_metadata=True,
            generated_by_oduit=generated_by_oduit,
            warnings=warnings,
            remediation=[
                "Fix or remove the invalid sidecar, then regenerate the "
                "technical documentation with oduit."
            ],
        )

    warnings = list(warnings)
    stored_addon_root = _resolve_metadata_path(
        metadata.addon_root,
        base_dir=storage_base,
    )
    if stored_addon_root != root:
        warnings.append("Metadata addon_root differs from current addon root.")

    status = TechnicalDocumentationStatus(
        module=module,
        addon_root=display_root,
        doc_path=display_doc,
        metadata_path=display_metadata,
        status="missing_document",
        has_document=has_document,
        has_metadata=True,
        generated_by_oduit=generated_by_oduit or True,
        generated_block_count=len(metadata.generated_blocks),
        created_at=metadata.created_at,
        last_generated_at=metadata.last_generated_at,
        generation_count=metadata.generation_count,
        generation_options=dict(metadata.generation_options or {}),
        evidence_counts=dict(metadata.evidence_counts or {}),
        template=metadata.template,
        warnings=warnings,
    )

    if not has_document:
        status.remediation.append(
            "Restore or regenerate the missing Markdown document."
        )
        return status

    current_document = compute_document_snapshot(doc_path)
    current_source = compute_source_snapshot(root, module=module)
    stored_document = metadata.document_snapshot
    stored_source = metadata.source_snapshot
    if stored_document is None or stored_source is None:
        status.status = "metadata_invalid"
        status.warnings.append(
            "Documentation metadata is missing source or document snapshots."
        )
        status.remediation.append(
            "Regenerate the technical documentation with oduit to rebuild "
            "tracking metadata."
        )
        return status

    status.generated_by_oduit = True
    status.document_edited_since_last_generation = (
        current_document.fingerprint != stored_document.fingerprint
    )
    status.source_changed_since_last_generation = (
        current_source.fingerprint != stored_source.fingerprint
    )

    try:
        parsed_blocks = parse_generated_blocks(doc_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        parsed_blocks = []
        status.warnings.append(f"Failed to parse managed markdown blocks: {exc}")
    parsed_by_id = {block.id: block for block in parsed_blocks}
    expected_by_id = {block.id: block for block in metadata.generated_blocks}
    status.generated_block_count = len(parsed_blocks)
    status.missing_generated_blocks = sorted(
        block_id for block_id in expected_by_id if block_id not in parsed_by_id
    )
    status.unknown_generated_blocks = sorted(
        block_id for block_id in parsed_by_id if block_id not in expected_by_id
    )
    status.edited_generated_blocks = sorted(
        block_id
        for block_id, parsed in parsed_by_id.items()
        if parsed.metadata.get("content_sha256") != sha256_text(parsed.body)
    )
    if status.source_changed_since_last_generation:
        status.stale_generated_blocks = sorted(
            block_id
            for block_id in expected_by_id
            if block_id not in status.edited_generated_blocks
        )
    else:
        status.stale_generated_blocks = []
    status.generated_blocks_up_to_date = (
        not status.stale_generated_blocks
        and not status.edited_generated_blocks
        and not status.missing_generated_blocks
    )
    (
        status.changed_files,
        status.added_files,
        status.removed_files,
    ) = _diff_source_files(stored_source, current_source)

    if (
        not status.document_edited_since_last_generation
        and not status.source_changed_since_last_generation
        and status.generated_blocks_up_to_date
    ):
        status.status = "up_to_date"
        status.up_to_date = True
        return status

    if status.edited_generated_blocks:
        status.status = "generated_blocks_edited"
        status.remediation.append(
            "Resolve manual edits inside managed generated blocks "
            "or force-refresh them."
        )
        return status

    if status.stale_generated_blocks:
        status.status = "generated_blocks_stale"
        status.remediation.append(
            "Run technical documentation refresh to update "
            "stale managed generated blocks."
        )
        return status

    if status.document_edited_since_last_generation and (
        not status.source_changed_since_last_generation
    ):
        status.status = "document_edited"
        status.remediation.append(
            "Compare the Markdown edits before overwriting with a fresh generation."
        )
        return status

    if status.source_changed_since_last_generation and (
        not status.document_edited_since_last_generation
    ):
        status.status = "source_changed"
        status.remediation.append(
            "Regenerate or manually review the architecture document."
        )
        return status

    status.status = "source_and_document_changed"
    status.remediation.append(
        "Review both the source changes and manual document edits before "
        "overwriting the tracked document."
    )
    return status


def inspect_all_technical_documentation_statuses(
    *,
    addons_path: str,
    select_dir: str | None = None,
    path_base_dir: Path | None = None,
    documentation_policy: DocumentationDirectoryPolicy | None = None,
) -> list[TechnicalDocumentationStatus]:
    """Scan configured addons and return status for each addon."""

    statuses: list[TechnicalDocumentationStatus] = []
    policy = documentation_policy or DocumentationDirectoryPolicy(
        configured=False,
        allowed_dirs=(),
    )
    for module, addon_root in _iter_addon_roots(
        addons_path,
        select_dir=select_dir,
        path_base_dir=path_base_dir,
    ):
        if not policy.is_allowed(addon_root):
            continue
        statuses.append(
            inspect_technical_documentation_status(
                addon_root=addon_root,
                module=module,
                path_base_dir=path_base_dir,
            )
        )
    return sorted(statuses, key=lambda item: (item.module, item.addon_root))


def technical_doc_needs_action(status: TechnicalDocumentationStatus) -> bool:
    """Return whether a status still needs technical-documentation work."""

    return status.status != "up_to_date"


def select_next_technical_doc_status(
    statuses: list[TechnicalDocumentationStatus],
) -> TechnicalDocumentationStatus | None:
    """Select the next addon that should receive technical-doc attention."""

    candidates = [status for status in statuses if technical_doc_needs_action(status)]
    if not candidates:
        return None
    return sorted(
        candidates,
        key=lambda item: (
            TECHNICAL_DOC_STATUS_RANK.get(item.status, 500),
            item.module,
            item.addon_root,
        ),
    )[0]


def parse_markdown_table(text: str) -> list[list[str]] | None:
    """Parse a markdown table into a list of rows, excluding separator row."""

    lines = [
        line.strip() for line in text.replace("\r\n", "\n").split("\n") if line.strip()
    ]
    if len(lines) < 2:
        return None

    def _split(line: str) -> list[str] | None:
        if "|" not in line:
            return None
        raw = line.strip()
        if raw.startswith("|"):
            raw = raw[1:]
        if raw.endswith("|"):
            raw = raw[:-1]
        return [cell.strip() for cell in raw.split("|")]

    header = _split(lines[0])
    separator = _split(lines[1])
    if header is None or separator is None or len(header) != len(separator):
        return None
    if any(not re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in separator):
        return None
    rows = [header]
    for line in lines[2:]:
        cells = _split(line)
        if cells is None:
            return None
        rows.append(cells)
    return rows


def normalize_markdown_for_significance(text: str) -> str:
    """Normalize markdown so spacing/alignment-only changes become equal."""

    table_rows = parse_markdown_table(text)
    if table_rows is not None:
        return "\n".join("|".join(cell.strip() for cell in row) for row in table_rows)

    normalized_lines: list[str] = []
    for raw_line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        line = raw_line.rstrip()
        stripped = line.strip()
        if stripped.startswith("<!--") and "oduit:" in stripped:
            continue
        if stripped == "":
            if normalized_lines and normalized_lines[-1] == "":
                continue
            normalized_lines.append("")
            continue
        normalized_lines.append(stripped)
    return "\n".join(normalized_lines).strip()


def _render_diff(old_text: str, new_text: str) -> str | None:
    diff_lines = list(
        unified_diff(
            old_text.splitlines(),
            new_text.splitlines(),
            fromfile="report_snapshot",
            tofile="current_evidence",
            lineterm="",
        )
    )
    if not diff_lines:
        return None
    return "\n".join(diff_lines)


def diff_report_against_evidence(
    *,
    addon_root: str | Path,
    module: str,
    path_base_dir: Path | None = None,
    include_diff: bool = False,
    significant_only: bool = False,
) -> TechnicalEvidenceDiffResult:
    """Diff report snapshot blocks against the current evidence document."""

    root = Path(addon_root).resolve(strict=False)
    report_path, _ = technical_doc_paths(root)
    evidence_path, evidence_metadata_path = technical_evidence_paths(root)
    storage_base = (
        path_base_dir.resolve(strict=False)
        if path_base_dir is not None
        else Path.cwd().resolve(strict=False)
    )
    result = TechnicalEvidenceDiffResult(
        module=module,
        addon_root=_portable_path(root, base_dir=storage_base),
        report_path=_portable_path(report_path, base_dir=storage_base),
        evidence_path=_portable_path(evidence_path, base_dir=storage_base),
        evidence_metadata_path=_portable_path(
            evidence_metadata_path, base_dir=storage_base
        ),
        status="up_to_date",
    )
    if not report_path.exists():
        result.status = "missing_report"
        result.remediation.append(
            "Generate the report with docs technical-report first."
        )
        return result
    if not evidence_path.exists() or not evidence_metadata_path.exists():
        result.status = "missing_evidence"
        result.remediation.append(
            "Run oduit docs technical-evidence"
            f" @addons/{module} --output-in-addon first."
        )
        return result

    evidence_metadata, metadata_warnings = load_technical_evidence_metadata(
        evidence_metadata_path
    )
    result.warnings.extend(metadata_warnings)
    if evidence_metadata is None:
        result.status = "invalid"
        return result
    result.current_evidence_version = evidence_metadata.evidence_version

    try:
        evidence_blocks = parse_generated_blocks(
            evidence_path.read_text(encoding="utf-8")
        )
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        result.status = "invalid"
        result.warnings.append(f"Failed to parse evidence markdown: {exc}")
        return result
    evidence_by_id = {block.id: block for block in evidence_blocks}

    try:
        report_snapshots = parse_evidence_snapshot_blocks(
            report_path.read_text(encoding="utf-8")
        )
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        result.status = "invalid"
        result.entries.append(
            TechnicalEvidenceDiffEntry(
                block_id="__marker__",
                status="marker_invalid",
                significant=True,
                message=str(exc),
            )
        )
        result.warnings.append(str(exc))
        return result

    entries: list[TechnicalEvidenceDiffEntry] = []
    for snapshot in report_snapshots:
        snapshot_sha = snapshot.metadata.get("snapshot_sha256")
        snapshot_sha_str = snapshot_sha if isinstance(snapshot_sha, str) else None
        current_snapshot_sha = sha256_text(snapshot.body)
        entry = TechnicalEvidenceDiffEntry(
            block_id=snapshot.block_id,
            renderer=snapshot.renderer,
            old_evidence_version=snapshot.evidence_version,
            current_evidence_version=evidence_metadata.evidence_version,
            old_source_sha256=(
                snapshot.metadata.get("source_sha256")
                if isinstance(snapshot.metadata.get("source_sha256"), str)
                else None
            ),
            old_content_sha256=(
                snapshot.metadata.get("content_sha256")
                if isinstance(snapshot.metadata.get("content_sha256"), str)
                else None
            ),
            snapshot_sha256=snapshot_sha_str,
            current_snapshot_sha256=current_snapshot_sha,
        )
        current_block = evidence_by_id.get(snapshot.block_id)
        if current_snapshot_sha != snapshot_sha_str:
            entry.status = "snapshot_edited"
            entry.significant = True
            entry.message = "Snapshot body differs from recorded snapshot_sha256."
            entries.append(entry)
            continue
        if current_block is None:
            entry.status = "current_block_missing"
            entry.significant = True
            entry.message = "Referenced evidence block does not exist in evidence file."
            entries.append(entry)
            continue
        entry.current_source_sha256 = (
            current_block.metadata.get("source_sha256")
            if isinstance(current_block.metadata.get("source_sha256"), str)
            else None
        )
        entry.current_content_sha256 = (
            current_block.metadata.get("content_sha256")
            if isinstance(current_block.metadata.get("content_sha256"), str)
            else sha256_text(current_block.body)
        )
        stale = (
            entry.old_source_sha256 != entry.current_source_sha256
            or entry.old_content_sha256 != entry.current_content_sha256
        )
        if not stale:
            entry.status = "unchanged"
            entries.append(entry)
            continue

        normalized_snapshot = normalize_markdown_for_significance(snapshot.body)
        normalized_current = normalize_markdown_for_significance(current_block.body)
        entry.significant = normalized_snapshot != normalized_current
        entry.status = (
            "snapshot_stale" if entry.significant else "snapshot_stale_insignificant"
        )
        if include_diff:
            entry.diff = _render_diff(snapshot.body, current_block.body)
        entries.append(entry)

    result.snapshot_count = len(report_snapshots)
    if significant_only:
        entries = [entry for entry in entries if entry.significant]
    result.entries = entries
    result.stale_count = sum(
        1
        for entry in entries
        if entry.status in {"snapshot_stale", "snapshot_stale_insignificant"}
    )
    result.edited_snapshot_count = sum(
        1 for entry in entries if entry.status == "snapshot_edited"
    )
    result.missing_current_block_count = sum(
        1 for entry in entries if entry.status == "current_block_missing"
    )
    if any(entry.status == "snapshot_edited" for entry in entries):
        result.status = "edited_snapshots"
    elif any(
        entry.status in {"snapshot_stale", "current_block_missing"} for entry in entries
    ):
        result.status = "stale"
    else:
        result.status = "up_to_date"
    return result


